 token_hash VARCHAR(64) PRIMARY KEY,
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
 redeemed_by UUID REFERENCES users(id),
 redeemed_at TIMESTAMP WITH TIME ZONE,
 revoked BOOLEAN NOT NULL DEFAULT FALSE
);
